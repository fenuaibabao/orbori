// One-off: turns Natural Earth land (world-atlas, public domain) into one SVG path
// in a 360×180 equirectangular box (x = lon + 180, y = 90 − lat). Output is committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const r = (n) => Math.round(n * 10) / 10;
let d = '';
const ring = (pts) => { d += 'M' + pts.map(([lon, lat]) => `${r(lon + 180)},${r(90 - lat)}`).join('L') + 'Z'; };
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of polys) for (const rg of p) ring(rg);
}
writeFileSync(new URL('../src/data/world-path.ts', import.meta.url), `/** Land outline (Natural Earth 1:110m, public domain) in a 360×180 equirectangular box. Generated by scripts/build-world.mjs. */\nexport const WORLD_PATH = ${JSON.stringify(d)};\n`);
console.log('world path chars', d.length);
