'use client';
import Link from 'next/link';
import { useEffect, useState } from 'react';
import { useAuth } from '@/lib/auth';
import { usePlus } from '@/lib/plus';
import { localToday, type Profile } from '@/lib/store';

/** The reading's closing question, used as the journal prompt. */
export function closingQuestion(text: string): string | null {
  const m = text.trim().match(/([^.!?\n]*\?)\s*$/);
  return m ? m[1].trim() : null;
}

/** Today's personal reading, written by AI from the Council. Hidden until the AI key is set up. */
export function AiReading({ profile, onQuestion }: { profile: Profile; onQuestion?: (q: string | null) => void }) {
  const { user, ready: authReady } = useAuth();
  const { plus, ready: plusReady } = usePlus();
  const [enabled, setEnabled] = useState<boolean | null>(null);
  const [text, setText] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    fetch('/api/reading').then((r) => r.json()).then((d) => setEnabled(!!d.enabled)).catch(() => setEnabled(false));
  }, []);

  useEffect(() => {
    if (!enabled || !user || !plus) return;
    const { date, timeZone } = localToday();
    const key = `orbori.ai.${user.id}.${date}`;
    try { const hit = sessionStorage.getItem(key); if (hit) { setText(hit); return; } } catch { /* storage blocked */ }
    fetch('/api/reading', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ input: profile.input, date, timeZone }) })
      .then(async (r) => {
        const d = await r.json();
        if (!r.ok) throw new Error(d.error);
        setText(d.body);
        try { sessionStorage.setItem(key, d.body); } catch { /* storage blocked */ }
      })
      .catch(() => setErr('Your reading is taking a moment. Refresh in a minute.'));
  }, [enabled, user, plus, profile]);

  useEffect(() => { if (text) onQuestion?.(closingQuestion(text)); }, [text, onQuestion]);

  if (!enabled || !authReady || (user && !plusReady)) return null;

  return (
    <section aria-labelledby="ai-reading" className="flex flex-col gap-3 rounded-3xl border border-gold bg-night p-5 lg:col-span-3">
      <div className="flex items-baseline justify-between gap-3">
        <h2 id="ai-reading" className="font-display text-lg font-bold">Your reading</h2>
        <span className="font-mono text-[10px] tracking-[0.1em] text-gold-lite">WRITTEN BY AI FROM YOUR COUNCIL</span>
      </div>
      {!user ? (
        <p className="text-sm text-muted">A short personal reading that weaves all seven voices together. <Link href={`/signin?next=${encodeURIComponent('/today')}`} className="text-gold-lite">Sign in</Link> to get yours.</p>
      ) : !plus ? (
        <p className="text-sm text-muted">A short personal reading that weaves all seven voices together, written fresh each day. Part of <Link href="/plus" className="text-gold-lite">Orbori Plus</Link>.</p>
      ) : text ? (
        <>
          {text.split(/\n\s*\n/).map((p, i) => <p key={i} className="text-[15px] leading-relaxed">{p.trim()}</p>)}
          <p className="text-xs text-dim">Generated by AI from Orbori&apos;s calculations. It offers reflections, not predictions or advice.</p>
        </>
      ) : err ? (
        <p className="text-sm text-muted">{err}</p>
      ) : (
        <div className="flex flex-col gap-2" aria-label="Writing your reading">
          {[100, 92, 96, 60].map((w) => <span key={w} className="h-3.5 animate-pulse rounded bg-deep" style={{ width: `${w}%` }} />)}
        </div>
      )}
    </section>
  );
}
